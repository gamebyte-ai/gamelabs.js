#!/usr/bin/env node
/**
 * Generate-playable-assets
 *
 * Walks an example's assets/ directory, encodes every file as a base64 data: URI,
 * and emits a TS module that maps filename-stem -> data URI. The playable entry
 * point imports this module and passes each value into AssetManager.load() as the
 * `url` argument (data URIs work natively in fetch, Pixi Assets, THREE loaders).
 *
 * Usage:
 *   node scripts/generate-playable-assets.mjs --example=2048
 *   node scripts/generate-playable-assets.mjs --src=examples/2048/assets --out=examples/2048/src/generated/PlayableAssets.ts
 *
 * Bundle-size hint: every byte counts twice (base64 is ~1.33x). For audio, prefer
 * short mono OGG/MP3 over WAV. The script prints a per-file size table.
 */
import { readdir, readFile, mkdir, writeFile, stat } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { dirname, resolve, extname, basename, relative } from "node:path";

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const repoRoot = resolve(__dirname, "..");

const MIME_BY_EXT = {
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".jpeg": "image/jpeg",
  ".webp": "image/webp",
  ".gif": "image/gif",
  ".svg": "image/svg+xml",
  ".wav": "audio/wav",
  ".mp3": "audio/mpeg",
  ".ogg": "audio/ogg",
  ".m4a": "audio/mp4",
  ".json": "application/json",
  ".glb": "model/gltf-binary",
  ".gltf": "model/gltf+json",
  ".txt": "text/plain",
};

function parseArgs(argv) {
  const out = {};
  for (const arg of argv.slice(2)) {
    const m = arg.match(/^--([^=]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

async function walk(dir, acc = []) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = resolve(dir, entry.name);
    if (entry.isDirectory()) await walk(full, acc);
    else if (entry.isFile()) acc.push(full);
  }
  return acc;
}

function toIdent(stem) {
  // filename stem -> safe JS identifier: "sfx_move" stays, "ui-button" -> "ui_button"
  return stem.replace(/[^a-zA-Z0-9_$]/g, "_");
}

function fmtBytes(n) {
  if (n < 1024) return `${n} B`;
  if (n < 1024 * 1024) return `${(n / 1024).toFixed(1)} KB`;
  return `${(n / 1024 / 1024).toFixed(2)} MB`;
}

async function main() {
  const args = parseArgs(process.argv);

  let srcDir;
  let outFile;
  if (args.example) {
    srcDir = resolve(repoRoot, "examples", args.example, "assets");
    outFile = resolve(repoRoot, "examples", args.example, "src/generated/PlayableAssets.ts");
  } else if (args.template) {
    srcDir = resolve(repoRoot, "templates", args.template, "assets");
    outFile = resolve(repoRoot, "templates", args.template, "src/generated/PlayableAssets.ts");
  } else if (args.src && args.out) {
    srcDir = resolve(repoRoot, args.src);
    outFile = resolve(repoRoot, args.out);
  } else {
    console.error("Usage: --example=<name>  OR  --template=<name>  OR  --src=<dir> --out=<file>");
    process.exit(1);
  }

  let srcExists = true;
  try {
    const s = await stat(srcDir);
    if (!s.isDirectory()) throw new Error("not a directory");
  } catch {
    srcExists = false;
  }

  const files = srcExists ? (await walk(srcDir)).sort() : [];
  if (!srcExists) {
    console.log(`No assets/ directory at ${relative(repoRoot, srcDir)} — emitting empty registry.`);
  } else if (files.length === 0) {
    console.log(`assets/ directory is empty — emitting empty registry.`);
  }

  const entries = [];
  let totalRaw = 0;
  let totalEncoded = 0;

  console.log(`Encoding ${files.length} files from ${relative(repoRoot, srcDir)}:`);
  for (const file of files) {
    const ext = extname(file).toLowerCase();
    const mime = MIME_BY_EXT[ext];
    if (!mime) {
      console.warn(`  skip ${relative(srcDir, file)} (unknown extension ${ext})`);
      continue;
    }
    const buf = await readFile(file);
    const b64 = buf.toString("base64");
    const dataUri = `data:${mime};base64,${b64}`;
    const ident = toIdent(basename(file, ext));
    entries.push({ ident, dataUri, relPath: relative(srcDir, file), raw: buf.length, encoded: dataUri.length });
    totalRaw += buf.length;
    totalEncoded += dataUri.length;
    console.log(`  ${ident.padEnd(24)} ${fmtBytes(buf.length).padStart(10)} -> ${fmtBytes(dataUri.length).padStart(10)}`);
  }
  console.log(`Total raw: ${fmtBytes(totalRaw)}, encoded: ${fmtBytes(totalEncoded)}`);

  const dupes = new Set();
  for (const e of entries) {
    if (dupes.has(e.ident)) {
      console.error(`Duplicate identifier "${e.ident}" — rename one of the files.`);
      process.exit(1);
    }
    dupes.add(e.ident);
  }

  const header = [
    "// AUTO-GENERATED by scripts/generate-playable-assets.mjs",
    "// Do not edit by hand. Regenerate with: npm run playable:assets:<example>",
    "",
    "/* eslint-disable */",
    "",
  ].join("\n");

  const body = [
    "export const PlayableAssets = {",
    ...entries.map((e) => `  ${JSON.stringify(e.ident)}: ${JSON.stringify(e.dataUri)},`),
    "} as const;",
    "",
    "export type PlayableAssetKey = keyof typeof PlayableAssets;",
    "",
  ].join("\n");

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, header + body, "utf8");
  console.log(`Wrote ${relative(repoRoot, outFile)}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
